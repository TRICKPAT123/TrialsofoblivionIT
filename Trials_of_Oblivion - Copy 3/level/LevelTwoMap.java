    private static int[][] createConnectedMap(int[][]... sections) {
        int totalRows = sections[0].length;
        int totalCols = 0;
        
        for (int[][] section : sections) {
            totalCols += section[0].length;
        }
        
        int[][] combined = new int[totalRows][totalCols];
        
        int currentCol = 0;
        for (int[][] section : sections) {
            for (int y = 0; y < totalRows; y++) {
                System.arraycopy(section[y], 0, combined[y], currentCol, section[y].length);
            }
            currentCol += section[0].length;
        }
        
        return combined;
    }
